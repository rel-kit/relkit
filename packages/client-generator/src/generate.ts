import { CONTRACT_VERSION, GENERATOR_VERSION } from "@zsys/contracts";
import type { ApplicationGraph } from "@zsys/graph";
import {
  clientRoutes,
  mappedInputType,
  responseType,
  type ClientRoute,
  type ResponseContract,
} from "./generate-types.js";
import { acceptsMissingInput, routeMethod, runtimeHelpers } from "./generate-request.js";

/** Generates a dependency-free, deterministic TypeScript client from graph HTTP routes. */
export function generateClient(graph: ApplicationGraph): string {
  const routes = clientRoutes(graph);
  const names = routeNames(routes);
  const lines = [
    "/* generated by @zsys/client-generator; do not edit */",
    `export const contractVersion = ${CONTRACT_VERSION} as const;`,
    `export const generatorVersion = ${GENERATOR_VERSION} as const;`,
    "export interface ClientOptions {",
    "  readonly baseUrl?: string;",
    "  readonly fetch?: typeof globalThis.fetch;",
    "}",
    "export type ClientResult<Status extends number, Data> = {",
    "  readonly status: Status;",
    "  readonly data: Data;",
    "};",
    "",
  ];
  for (const route of routes) lines.push(...routeTypes(route, names.get(route.trigger.id)!));
  lines.push("export interface ZsysClient {");
  for (const route of routes) {
    const name = names.get(route.trigger.id)!;
    const optional = acceptsMissingInput(route);
    lines.push(
      `  readonly ${name.method}: (input${optional ? "?" : ""}: ${name.type}Input) => Promise<${name.type}Result>;`,
    );
  }
  lines.push("}", "export type Client = ZsysClient;", "");
  lines.push(
    "export function createClient(options: ClientOptions = {}): ZsysClient {",
    '  const baseUrl = options.baseUrl ?? "";',
    "  const fetcher = options.fetch ?? globalThis.fetch;",
    "  return {",
  );
  for (const route of routes) lines.push(...routeMethod(route, names.get(route.trigger.id)!));
  lines.push("  };", "}", "", "export default createClient;", "");
  lines.push(...runtimeHelpers());
  return `${lines.join("\n")}\n`;
}

/** Alias with an explicit output-format name for compiler callers. */
export const generateClientTypeScript = generateClient;

interface RouteNames {
  readonly method: string;
  readonly type: string;
}

function routeNames(routes: readonly ClientRoute[]): ReadonlyMap<string, RouteNames> {
  const usedMethods = new Set<string>();
  const usedTypes = new Set<string>();
  return new Map(
    routes.map((route) => {
      const base = pascalCase(route.trigger.id);
      const type = unique(base, usedTypes);
      const method = unique(lowerFirst(type), usedMethods);
      return [route.trigger.id, { method, type }];
    }),
  );
}

function routeTypes(route: ClientRoute, names: RouteNames): string[] {
  const responses = route.responses.map((response, index) => {
    const type = responseType(route, response);
    return `type ${names.type}Response${index} = ClientResult<${response.status}, ${type}>;`;
  });
  const success = route.responses
    .map((response, index) => (isSuccess(response) ? `${names.type}Response${index}` : ""))
    .filter(Boolean);
  const errors = route.responses
    .map((response, index) => (!isSuccess(response) ? `${names.type}Response${index}` : ""))
    .filter(Boolean);
  return [
    `export type ${names.type}Input = ${mappedInputType(route)};`,
    ...responses,
    `export type ${names.type}Success = ${success.join(" | ") || "never"};`,
    `export type ${names.type}Error = ${errors.join(" | ") || "never"};`,
    `export type ${names.type}Result = ${names.type}Success | ${names.type}Error;`,
    `export type ${names.type}Status = ${names.type}Result["status"];`,
    "",
  ];
}

function isSuccess(response: ResponseContract): boolean {
  return response.kind === "success" || (response.status >= 200 && response.status < 300);
}

function pascalCase(value: string): string {
  const words = value.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const result = words.map((word) => word[0]!.toUpperCase() + word.slice(1)).join("");
  return /^[A-Za-z_]/.test(result) ? result : `Route${result}`;
}

function lowerFirst(value: string): string {
  return value[0]!.toLowerCase() + value.slice(1);
}

function unique(base: string, used: Set<string>): string {
  let value = base;
  let suffix = 2;
  while (used.has(value)) value = `${base}${suffix++}`;
  used.add(value);
  return value;
}
