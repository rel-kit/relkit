import { join } from "node:path";
import { canonicalJson } from "@relkit/contracts";
import {
  GENERATED_ARTIFACT_FILES,
  type GeneratedOutputs,
  type LoadedToolingConfig,
} from "@relkit/compiler";
import { createDiagnostic, sortDiagnostics, type Diagnostic } from "@relkit/diagnostics";
import { Effect } from "effect";
import { cliOriginalError } from "../cli-errors.js";
import { observeCli, runCliEffect } from "../cli-runtime.js";
import { CliCompiler, compilerLayer } from "../services/compiler.service.js";
import { emptyCheckOutputs, safeMessage } from "./check-support.js";
import type { CheckResult } from "./check-result.types.js";
export type { CheckResult } from "./check-result.types.js";

/**
 * Publishes compilation output, retaining a diagnostic-only path for failed graphs.
 * @param projectRoot - Root used to redact artifact-write diagnostics.
 * @param generatedDirectory - Compilation's output directory.
 * @param diagnostics - Compiler diagnostics in any order.
 * @param outputs - Authored generated bytes, defaulting to a failed compilation.
 * @param graphHash - Validated graph identity when available.
 * @param config - Validated compiler settings when available.
 * @returns A frozen check result; only expected artifact I/O errors become diagnostics.
 */
export const emitCheckResultEffect = Effect.fn("Project.emitCheckResult")(
  function* (
    projectRoot: string,
    generatedDirectory: string,
    diagnostics: readonly Diagnostic[],
    outputs: GeneratedOutputs = emptyCheckOutputs(diagnostics),
    graphHash?: string,
    config?: LoadedToolingConfig,
  ): Effect.fn.Return<CheckResult, never, CliCompiler> {
    const compiler = yield* CliCompiler;
    let stable = sortDiagnostics(diagnostics);
    let nextOutputs =
      outputs.diagnostics === ""
        ? { ...outputs, diagnostics: `${canonicalJson(stable)}\n` }
        : outputs;
    const hasCompilationErrors = stable.some((diagnostic) => diagnostic.severity === "error");
    const writing = hasCompilationErrors
      ? compiler
          .writeChanged(
            join(generatedDirectory, GENERATED_ARTIFACT_FILES.diagnostics),
            nextOutputs.diagnostics,
          )
          .pipe(Effect.asVoid)
      : compiler.writeArtifacts(nextOutputs, { directory: generatedDirectory }).pipe(Effect.asVoid);
    const written = yield* writing.pipe(Effect.result);
    if (written._tag === "Failure") {
      stable = sortDiagnostics([
        ...stable,
        createDiagnostic({
          code: "RELKIT_ARTIFACT_WRITE_FAILED",
          severity: "error",
          message: safeMessage(cliOriginalError(written.failure), projectRoot),
        }),
      ]);
      nextOutputs = { ...nextOutputs, diagnostics: `${canonicalJson(stable)}\n` };
    }
    const hasErrors = stable.some((diagnostic) => diagnostic.severity === "error");
    return Object.freeze({
      ok: !hasErrors,
      activatable: !hasErrors && nextOutputs.manifest !== "",
      projectRoot,
      generatedDirectory,
      ...(graphHash === undefined ? {} : { graphHash }),
      ...(config === undefined ? {} : { config }),
      diagnostics: Object.freeze(stable),
      outputs: nextOutputs,
    });
  },
  (
    effect,
    _projectRoot: string,
    _generatedDirectory: string,
    _diagnostics: readonly Diagnostic[],
    _outputs: GeneratedOutputs = emptyCheckOutputs(_diagnostics),
    _graphHash?: string,
    _config?: LoadedToolingConfig,
  ) => observeCli("project.emitCheckResult", effect),
);

/**
 * Publishes compilation output at the public compatibility boundary.
 * @param projectRoot - Authored project root.
 * @param generatedDirectory - Artifact destination.
 * @param diagnostics - Compilation diagnostics.
 * @param outputs - Generated bytes.
 * @param graphHash - Optional validated graph hash.
 * @param config - Optional validated settings.
 * @returns A Promise resolving after content-aware publication.
 */
export function emitCheckResult(
  projectRoot: string,
  generatedDirectory: string,
  diagnostics: readonly Diagnostic[],
  outputs: GeneratedOutputs = emptyCheckOutputs(diagnostics),
  graphHash?: string,
  config?: LoadedToolingConfig,
): Promise<CheckResult> {
  return runCliEffect(
    emitCheckResultEffect(projectRoot, generatedDirectory, diagnostics, outputs, graphHash, config),
    compilerLayer,
  );
}
