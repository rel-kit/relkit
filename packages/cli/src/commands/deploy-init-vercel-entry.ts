/**
 * Renders the Vercel function entry `relkit deploy init vercel` writes to `api/relkit.mjs`. It
 * activates the built Node server once per function instance in function-host mode (no listener, no
 * background worker or scheduler loop), serves every request through it, answers Vercel Cron on
 * the authenticated cron endpoint with one drain of the durable backend, and after other requests
 * drains briefly through Vercel's `waitUntil` so that jobs and events submitted over HTTP run
 * without waiting for the next cron call.
 */
import { VERCEL_CRON_PATH } from "./deploy-init-vercel-crons.js";

/** Time one cron call may spend on schedules, job runs and event deliveries, in ms. */
export const VERCEL_CRON_BUDGET_MS = 50_000;
/** Longest a request waits for a cold instance to become ready, in ms. */
export const VERCEL_READY_BUDGET_MS = 25_000;
/** Time the drain after an ordinary request may spend, in ms. */
export const VERCEL_AFTER_REQUEST_BUDGET_MS = 5_000;

/**
 * Renders the function entry.
 * @returns JavaScript module source.
 */
export function vercelFunctionEntry(): string {
  return `// Generated by \`relkit deploy init vercel\`. Serves the RelKit Node production server as a
// Vercel function; \`relkit build --runtime node --target vercel\` writes the server it imports.
import { timingSafeEqual } from "node:crypto";
import { fileURLToPath } from "node:url";

// Functions keep no state between invocations: durable work lives in the external backend, no
// worker or scheduler loop runs in the instance, and Vercel terminates TLS in front of it.
process.env.NODE_ENV ??= "production";
process.env.RELKIT_DURABLE_STATE = "external";
process.env.RELKIT_WORKER_ROLE = "api";
process.env.RELKIT_TRUST_PROXY ??= "1";
process.chdir(fileURLToPath(new URL("../.relkit/build/", import.meta.url)));

const CRON_PATH = "${VERCEL_CRON_PATH}";
let activation;

/** Longest a request waits for a cold instance's providers before the server answers 503, in ms. */
const READY_BUDGET_MS = ${VERCEL_READY_BUDGET_MS};

/** Activates the server once per instance; a failed activation is retried by the next request. */
function relkit() {
  activation ??= import("../.relkit/build/server/index.js")
    .then((server) => server.activateRelkitApplication({ embedded: false, functionHost: true }))
    .catch((error) => {
      activation = undefined;
      throw error;
    });
  return activation;
}

/** Accepts only Vercel Cron's \`Authorization: Bearer <CRON_SECRET>\` header. */
function authorized(request) {
  const secret = process.env.CRON_SECRET;
  if (secret === undefined || secret.length < 16) return false;
  const expected = Buffer.from("Bearer " + secret);
  const actual = Buffer.from(request.headers.get("authorization") ?? "");
  return actual.length === expected.length && timingSafeEqual(actual, expected);
}

/** Lets work continue after the response, through the request context Vercel provides. */
function afterResponse(work) {
  const context = globalThis[Symbol.for("@vercel/request-context")]?.get?.();
  if (typeof context?.waitUntil === "function") context.waitUntil(work.catch(() => {}));
}

function problem(status, title, detail) {
  return Response.json({ type: "about:blank", title, status, detail }, { status, headers: { "content-type": "application/problem+json", "cache-control": "no-store" } });
}

async function handle(request) {
  const path = new URL(request.url).pathname;
  if (path === CRON_PATH || path.startsWith(CRON_PATH + "/")) {
    if (!authorized(request)) return problem(401, "Unauthorized", "Set CRON_SECRET (16 characters or more) on the project; Vercel Cron sends it.");
    const server = await relkit();
    const result = await server.drain({ budgetMs: ${VERCEL_CRON_BUDGET_MS} });
    return Response.json(result, { headers: { "cache-control": "no-store" } });
  }
  let server;
  try {
    server = await relkit();
  } catch (error) {
    console.error(error);
    return problem(503, "Service Unavailable", "The server failed to start; read the function logs.");
  }
  // A cold instance starts its providers on the first request; the server answers 503 until ready.
  await server.ready(READY_BUDGET_MS).catch(() => {});
  const response = await server.fetch(request);
  if (process.env.RELKIT_VERCEL_DRAIN_AFTER_REQUEST !== "0") afterResponse(server.drain({ budgetMs: ${VERCEL_AFTER_REQUEST_BUDGET_MS} }));
  return response;
}

export const GET = handle;
export const HEAD = handle;
export const POST = handle;
export const PUT = handle;
export const PATCH = handle;
export const DELETE = handle;
export const OPTIONS = handle;
`;
}
