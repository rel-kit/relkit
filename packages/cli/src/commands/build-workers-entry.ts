/**
 * Renders `server/worker.ts`, the entry of a `relkit build --runtime workers` bundle. Cloudflare
 * calls the default export's handlers; the server module is imported lazily from the first one,
 * because a Worker's global scope may not generate random values or set timers. The server runs in
 * function-host mode: no listener, no signal handlers and no background worker loop, since the
 * isolate only runs while a handler does. String bindings (variables and secrets) become
 * `process.env` entries before activation, so the server reads its configuration as it does on Bun
 * and Node.
 *
 * Durable work (jobs, schedules and events in the Postgres backend) runs in the server's `drain`,
 * which three handlers call: `queue` for each batch of the `RELKIT_WORK` queue, which every
 * request that may have submitted work wakes with one message; `scheduled` for the Cron Trigger,
 * which claims due schedule occurrences and picks up retries; and nothing else, so no background
 * loop outlives a handler. A failed drain retries the queue batch, so wake-ups are at least once.
 */

/** Longest a request waits for a cold isolate's providers before the server answers 503, in ms. */
export const WORKERS_READY_BUDGET_MS = 25_000;
/** Time one queue batch or Cron Trigger may spend on schedules, job runs and deliveries, in ms. */
export const WORKERS_DRAIN_BUDGET_MS = 25_000;
/** Queue binding whose messages wake the Worker to drain durable work. */
export const WORKERS_WORK_QUEUE_BINDING = "RELKIT_WORK";

/** What the graph needs from the Worker entry. */
export interface WorkersEntryOptions {
  /** Re-export the Durable Object class that holds realtime state. */
  readonly durableObjectRealtime?: boolean;
}

/**
 * Renders the Workers entry module.
 * @returns JavaScript module source (valid TypeScript), bundled into `server/index.js`.
 */
export function workersEntrySource(options: WorkersEntryOptions = {}): string {
  return `// Generated by \`relkit build --runtime workers\`. Cloudflare calls the exported handlers.
${options.durableObjectRealtime === true ? 'export { RelkitRealtimeState } from "@relkit/cloudflare/workers";\n' : ""}const SAFE_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);
let activation;
let environmentLoaded = false;

/** Copies string bindings into process.env once per isolate; the build is a production build. */
function loadEnvironment(env) {
  // Providers read bindings (KV, R2, queues, Durable Objects) through relkit/runtime/workers.
  globalThis[Symbol.for("relkit.workers.bindings")] = env ?? {};
  if (environmentLoaded) return;
  environmentLoaded = true;
  for (const [name, value] of Object.entries(env ?? {}))
    if (typeof value === "string" && process.env[name] === undefined) process.env[name] = value;
  process.env.RELKIT_ENV ??= "production";
  // A Worker keeps no local state and runs no background loop between invocations.
  process.env.RELKIT_DURABLE_STATE = "external";
  process.env.RELKIT_WORKER_ROLE = "api";
}

/** Activates the server once per isolate; a failed activation is retried by the next event. */
function relkit(env) {
  loadEnvironment(env);
  activation ??= import("./index.ts")
    .then((server) => server.activateRelkitApplication({ embedded: false, functionHost: true }))
    .catch((error) => {
      activation = undefined;
      throw error;
    });
  return activation;
}

function problem(status, title, detail) {
  return Response.json({ type: "about:blank", title, status, detail }, { status, headers: { "content-type": "application/problem+json", "cache-control": "no-store" } });
}

export default {
  async fetch(request, env, context) {
    let server;
    try {
      server = await relkit(env);
    } catch (error) {
      console.error(error);
      return problem(503, "Service Unavailable", "The server failed to start; read the Worker logs.");
    }
    // A cold isolate starts its providers on the first request; the server answers 503 until ready.
    await server.ready(${WORKERS_READY_BUDGET_MS}).catch(() => {});
    const response = await server.fetch(request, env);
    // A request that may have submitted jobs or published events wakes a queue consumer to run them.
    const queue = env?.${WORKERS_WORK_QUEUE_BINDING};
    if (!SAFE_METHODS.has(request.method) && typeof queue?.send === "function")
      context.waitUntil(queue.send({ kind: "drain", at: Date.now() }).catch((error) => console.error(error)));
    return response;
  },

  async queue(batch, env) {
    try {
      const server = await relkit(env);
      await server.drain({ budgetMs: ${WORKERS_DRAIN_BUDGET_MS} });
      batch.ackAll();
    } catch (error) {
      console.error(error);
      batch.retryAll();
    }
  },

  async scheduled(controller, env) {
    const server = await relkit(env);
    await server.drain({ budgetMs: ${WORKERS_DRAIN_BUDGET_MS} });
  },
};
`;
}

/**
 * Reads what the Worker entry must provide from the compiled graph.
 * @param graph - Compiled application graph.
 * @returns The entry options.
 */
export function workersEntryOptions(graph: {
  readonly nodes: readonly object[];
}): WorkersEntryOptions {
  const durableObjectRealtime = graph.nodes.some(
    (node) =>
      (node as { readonly kind?: string }).kind === "provider" &&
      (node as { readonly adapter?: { readonly adapterId?: string } }).adapter?.adapterId ===
        "cloudflare-durable-object-realtime",
  );
  return durableObjectRealtime ? { durableObjectRealtime } : {};
}
