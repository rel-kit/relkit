/**
 * Renders `server/worker.ts`, the entry of a `relkit build --runtime workers` bundle. Cloudflare
 * calls the default export's handlers; the server module is imported lazily from the first one,
 * because a Worker's global scope may not generate random values or set timers. The server runs in
 * function-host mode: no listener, no signal handlers and no background worker loop, since the
 * isolate only runs while a handler does. String bindings (variables and secrets) become
 * `process.env` entries before activation, so the server reads its configuration as it does on Bun
 * and Node.
 */

/** Longest a request waits for a cold isolate's providers before the server answers 503, in ms. */
export const WORKERS_READY_BUDGET_MS = 25_000;

/**
 * Renders the Workers entry module.
 * @returns JavaScript module source (valid TypeScript), bundled into `server/index.js`.
 */
export function workersEntrySource(): string {
  return `// Generated by \`relkit build --runtime workers\`. Cloudflare calls the exported handlers.
let activation;
let environmentLoaded = false;

/** Copies string bindings into process.env once per isolate; the build is a production build. */
function loadEnvironment(env) {
  // Providers read bindings (KV, R2, queues, Durable Objects) through relkit/runtime/workers.
  globalThis[Symbol.for("relkit.workers.bindings")] = env ?? {};
  if (environmentLoaded) return;
  environmentLoaded = true;
  for (const [name, value] of Object.entries(env ?? {}))
    if (typeof value === "string" && process.env[name] === undefined) process.env[name] = value;
  process.env.RELKIT_ENV ??= "production";
  // A Worker keeps no local state and runs no background loop between invocations.
  process.env.RELKIT_DURABLE_STATE = "external";
  process.env.RELKIT_WORKER_ROLE = "api";
}

/** Activates the server once per isolate; a failed activation is retried by the next event. */
function relkit(env) {
  loadEnvironment(env);
  activation ??= import("./index.ts")
    .then((server) => server.activateRelkitApplication({ embedded: false, functionHost: true }))
    .catch((error) => {
      activation = undefined;
      throw error;
    });
  return activation;
}

function problem(status, title, detail) {
  return Response.json({ type: "about:blank", title, status, detail }, { status, headers: { "content-type": "application/problem+json", "cache-control": "no-store" } });
}

export default {
  async fetch(request, env, context) {
    let server;
    try {
      server = await relkit(env);
    } catch (error) {
      console.error(error);
      return problem(503, "Service Unavailable", "The server failed to start; read the Worker logs.");
    }
    // A cold isolate starts its providers on the first request; the server answers 503 until ready.
    await server.ready(${WORKERS_READY_BUDGET_MS}).catch(() => {});
    return server.fetch(request, env);
  },
};
`;
}
