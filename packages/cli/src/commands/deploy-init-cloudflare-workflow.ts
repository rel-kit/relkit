/**
 * Renders the GitHub Actions workflow `relkit deploy init cloudflare` writes: on every push to
 * `main` it checks, type-checks and tests the project, creates the work queue when the Worker
 * needs one and it does not exist yet, and runs `wrangler deploy`, which builds the Workers bundle
 * first and provisions the KV namespaces and R2 buckets declared by binding name.
 */
import {
  CLOUDFLARE_WRANGLER_VERSION,
  workQueueName,
  type CloudflarePlan,
} from "./deploy-init-cloudflare-plan.js";

/**
 * Renders the workflow.
 * @param plan - Bindings and durable work from the graph.
 * @returns Workflow YAML.
 */
export function cloudflareWorkflow(plan: CloudflarePlan): string {
  const wrangler = `bunx wrangler@${CLOUDFLARE_WRANGLER_VERSION}`;
  const queue = workQueueName(plan);
  const queueStep = plan.durableWork
    ? `      - name: Create the work queue once
        run: ${wrangler} queues info ${queue} >/dev/null 2>&1 || ${wrangler} queues create ${queue}
`
    : "";
  return `# Generated by \`relkit deploy init cloudflare\`. Deploys the Worker on every push to main.
# Secrets: CLOUDFLARE_API_TOKEN (a token with Workers, Workers KV, R2 and Queues edit permissions).
# Variables: CLOUDFLARE_ACCOUNT_ID. Application secrets such as DATABASE_URL are set once with
# \`wrangler secret put\`.
name: Deploy to Cloudflare

on:
  push:
    branches: [main]
  workflow_dispatch:

concurrency:
  group: cloudflare-deploy
  cancel-in-progress: false

permissions:
  contents: read

jobs:
  deploy:
    runs-on: ubuntu-latest
    env:
      CLOUDFLARE_API_TOKEN: \${{ secrets.CLOUDFLARE_API_TOKEN }}
      CLOUDFLARE_ACCOUNT_ID: \${{ vars.CLOUDFLARE_ACCOUNT_ID }}
    steps:
      - uses: actions/checkout@v4
      - uses: oven-sh/setup-bun@v2
        with:
          bun-version: 1.3.10
      - run: bun install --frozen-lockfile
      - run: bun run check
      - run: bun run typecheck
      - run: bun run test
${queueStep}      - name: Build the Workers bundle and deploy
        run: ${wrangler} deploy
`;
}
