/**
 * Renders the files `relkit deploy init cloudflare` writes: `wrangler.jsonc` with the bindings the
 * compiled graph needs, the Worker entry `worker.mjs`, and a GitHub Actions workflow. Pure
 * renderers; the command writes them and never calls Cloudflare. KV namespaces and R2 buckets are
 * declared by binding name only, which wrangler provisions on the first deploy; the work queue is
 * created by the workflow (or `wrangler queues create`).
 */
import type { DeployInitFile } from "./deploy-init-railway.js";
import { cloudflareWorkflow } from "./deploy-init-cloudflare-workflow.js";
import {
  WORKERS_COMPATIBILITY_DATE,
  workQueueName,
  type CloudflarePlan,
} from "./deploy-init-cloudflare-plan.js";
import { WORKERS_WORK_QUEUE_BINDING } from "./build-workers-entry.js";
export * from "./deploy-init-cloudflare-plan.js";

/** Project-relative path of the Worker entry. */
export const CLOUDFLARE_WORKER_ENTRY = "worker.mjs";

/**
 * Renders every Cloudflare file.
 * @param plan - Bindings and durable work from the graph.
 * @returns Files in write order.
 */
export function cloudflareFiles(plan: CloudflarePlan): readonly DeployInitFile[] {
  return [
    { path: "wrangler.jsonc", content: wranglerConfig(plan) },
    { path: CLOUDFLARE_WORKER_ENTRY, content: cloudflareWorkerEntry() },
    { path: ".github/workflows/cloudflare-deploy.yml", content: cloudflareWorkflow(plan) },
  ];
}

/**
 * Renders `wrangler.jsonc`: the build command, the entry, `nodejs_compat`, `public/` as static
 * assets, and the KV, R2, Durable Object, queue and Cron bindings the graph needs.
 * @param plan - Bindings and durable work from the graph.
 * @returns JSONC source.
 */
export function wranglerConfig(plan: CloudflarePlan): string {
  const queue = workQueueName(plan);
  const config = {
    name: plan.name,
    main: CLOUDFLARE_WORKER_ENTRY,
    compatibility_date: WORKERS_COMPATIBILITY_DATE,
    compatibility_flags: ["nodejs_compat"],
    build: { command: "./node_modules/.bin/relkit build --runtime workers" },
    assets: { directory: ".relkit/build/public" },
    observability: { enabled: true },
    ...(plan.kv.length === 0 ? {} : { kv_namespaces: plan.kv.map((binding) => ({ binding })) }),
    ...(plan.r2.length === 0 ? {} : { r2_buckets: plan.r2.map((binding) => ({ binding })) }),
    ...(plan.realtime.length === 0
      ? {}
      : {
          durable_objects: {
            bindings: plan.realtime.map((name) => ({ name, class_name: "RelkitRealtimeState" })),
          },
          migrations: [{ tag: "relkit-realtime-v1", new_sqlite_classes: ["RelkitRealtimeState"] }],
        }),
    ...(plan.durableWork
      ? {
          queues: {
            producers: [{ binding: WORKERS_WORK_QUEUE_BINDING, queue }],
            consumers: [{ queue, max_batch_size: 10, max_batch_timeout: 1, max_retries: 10 }],
          },
          triggers: { crons: ["* * * * *"] },
        }
      : {}),
  };
  return `// Generated by \`relkit deploy init cloudflare\`. Bindings come from the application graph;
// rerun the command after adding caches, buckets, realtime or durable work. Secrets such as
// DATABASE_URL are set with \`wrangler secret put\`, never here.
${JSON.stringify(config, null, 2)}
`;
}

/**
 * Renders the Worker entry: it re-exports the handlers and Durable Objects that
 * `relkit build --runtime workers` writes, and is the place for the project's own handlers.
 * @returns JavaScript module source.
 */
export function cloudflareWorkerEntry(): string {
  return `// Generated by \`relkit deploy init cloudflare\`. The Worker's entry: the fetch, queue and
// scheduled handlers and the Durable Object classes come from the RelKit Workers build, which
// \`wrangler deploy\` runs first (see build.command in wrangler.jsonc).
export * from "./.relkit/build/server/index.js";
export { default } from "./.relkit/build/server/index.js";
`;
}
