/**
 * Renders the files `relkit deploy init vercel` writes: `vercel.json` (the build command, one Node
 * function that serves every path, cron entries derived from the project's schedules), the function
 * entry, an upload ignore list and a GitHub Actions workflow that deploys on push. Pure renderers;
 * the command writes them and never calls Vercel.
 */
import type { DeployInitFile } from "./deploy-init-railway.js";
import type { VercelCronPlan } from "./deploy-init-vercel-crons.js";
import { vercelFunctionEntry } from "./deploy-init-vercel-entry.js";

/** Vercel CLI release the generated workflow runs. */
export const VERCEL_CLI_VERSION = "65.11.0";
/** Project-relative path of the function entry. */
export const VERCEL_FUNCTION_ENTRY = "api/relkit.mjs";
/** Longest a function invocation may run, in seconds; also the cron drain's ceiling. */
export const VERCEL_MAX_DURATION = 60;

/**
 * Renders every Vercel file.
 * @param cron - Cron entries derived from the project's schedules.
 * @returns Files in write order.
 */
export function vercelFiles(cron: VercelCronPlan): readonly DeployInitFile[] {
  return [
    { path: "vercel.json", content: vercelConfig(cron) },
    { path: VERCEL_FUNCTION_ENTRY, content: vercelFunctionEntry() },
    { path: ".vercelignore", content: vercelIgnore() },
    { path: ".github/workflows/vercel-deploy.yml", content: vercelWorkflow() },
  ];
}

/**
 * Renders the project configuration. Vercel installs from the lockfile, builds the Node server,
 * serves `public/` from its CDN and rewrites every other path to the one function, which carries
 * the build output with it.
 * @param cron - Cron entries derived from the project's schedules.
 * @returns `vercel.json` source.
 */
export function vercelConfig(cron: VercelCronPlan): string {
  return `${JSON.stringify(
    {
      $schema: "https://openapi.vercel.sh/vercel.json",
      framework: null,
      installCommand: "bun install --frozen-lockfile",
      buildCommand: "./node_modules/.bin/relkit build --runtime node --target vercel",
      outputDirectory: ".relkit/build/public",
      functions: {
        [VERCEL_FUNCTION_ENTRY]: {
          maxDuration: VERCEL_MAX_DURATION,
          includeFiles: ".relkit/build/**",
        },
      },
      rewrites: [{ source: "/(.*)", destination: "/api/relkit" }],
      crons: cron.crons,
    },
    null,
    2,
  )}\n`;
}

/**
 * Renders the upload ignore list: Vercel builds from source, so local installs, build output,
 * state and secrets stay on the developer's machine.
 * @returns `.vercelignore` source.
 */
export function vercelIgnore(): string {
  return `node_modules
.relkit
.env
.env.*
!.env.example
coverage
*.log
`;
}

/**
 * Renders the workflow that checks the project and deploys it to production with the Vercel CLI on
 * push to `main`; Vercel builds it remotely from the uploaded source, as `vercel deploy` does
 * locally. It needs the `VERCEL_TOKEN` secret and the `VERCEL_ORG_ID` and `VERCEL_PROJECT_ID`
 * variables.
 * @returns Workflow YAML.
 */
export function vercelWorkflow(): string {
  const vercel = `bunx vercel@${VERCEL_CLI_VERSION}`;
  return `# Generated by \`relkit deploy init vercel\`. Deploys to Vercel on every push to main.
# Secrets: VERCEL_TOKEN (a Vercel access token). Variables: VERCEL_ORG_ID and VERCEL_PROJECT_ID
# (from .vercel/project.json after \`vercel link\`).
name: Deploy to Vercel

on:
  push:
    branches: [main]
  workflow_dispatch:

concurrency:
  group: vercel-deploy
  cancel-in-progress: false

permissions:
  contents: read

jobs:
  deploy:
    runs-on: ubuntu-latest
    env:
      VERCEL_ORG_ID: \${{ vars.VERCEL_ORG_ID }}
      VERCEL_PROJECT_ID: \${{ vars.VERCEL_PROJECT_ID }}
    steps:
      - uses: actions/checkout@v4
      - uses: oven-sh/setup-bun@v2
        with:
          bun-version: 1.3.10
      - uses: actions/setup-node@v4
        with:
          node-version: 24
      - run: bun install --frozen-lockfile
      - run: bun run check
      - run: bun run typecheck
      - run: bun run test
      - name: Build remotely and deploy to production
        run: ${vercel} deploy --prod --yes --token "\${{ secrets.VERCEL_TOKEN }}"
`;
}
