/**
 * Checks user-facing text against WRITING.md: the product is spelled "RelKit", and prose does not
 * use internal process terms. Code blocks, inline code and identifiers are not prose.
 */
import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import ts from "typescript";

/** One rule violation with its location. */
export interface UserTextFinding {
  readonly file: string;
  readonly line: number;
  readonly column: number;
  readonly rule: "spelling" | "banned-term";
  readonly text: string;
}

/** Internal process terms that user-facing text must not use. */
export const BANNED_TERMS = [
  "tuple",
  "certified",
  "readiness evidence",
  "receipt",
  "capsule",
  "cohort",
  "admission",
] as const;

const SPELLING = /\b(?:RELKIT|Relkit)\b/gu;
const BANNED = new RegExp(
  `\\b(?:${BANNED_TERMS.map((term) => `${term.replace(" ", "\\s+")}s?`).join("|")})\\b`,
  "giu",
);
/** The type namespace users augment keeps its historical spelling. */
const NAMESPACE = /\b(?:namespace\s+Relkit|Relkit\.[A-Z])/gu;
const GENERATED = /Generated by [^\n]*Do not edit|DO NOT EDIT/u;

/** A text region to check, with the offset of its first character in the source file. */
interface Region {
  readonly text: string;
  readonly offset: number;
}

/**
 * Lists the files each rule reads.
 * @param root - Repository root.
 * @returns Markdown pages, CLI source files and whether each page is generated.
 */
export function userTextFiles(root: string): {
  readonly markdown: readonly string[];
  readonly cli: readonly string[];
} {
  const tracked = Bun.spawnSync(["git", "ls-files", "-co", "--exclude-standard"], { cwd: root })
    .stdout.toString()
    .split("\n")
    .filter(Boolean);
  const markdown = tracked.filter(
    (path) =>
      /\.mdx?$/u.test(path) &&
      (["README.md", "CONTRIBUTING.md", "WRITING.md", "CHANGELOG.md"].includes(path) ||
        /^(?:packages|integrations\/packages)\/[^/]+\/README\.md$/u.test(path) ||
        /^templates\/default\/v1\/[^/]+\/README\.md$/u.test(path) ||
        path === "templates/README.md" ||
        path.startsWith("apps/docs/content/")),
  );
  const cli = tracked.filter(
    (path) =>
      /^packages\/(?:cli|create-relkit)\/src\/.*\.ts$/u.test(path) && !path.endsWith(".d.ts"),
  );
  return { markdown, cli };
}

/**
 * Checks every user-facing file in the repository.
 * @param root - Repository root.
 * @returns Findings sorted by file and position.
 */
export function checkUserText(root: string): UserTextFinding[] {
  const { markdown, cli } = userTextFiles(root);
  const findings: UserTextFinding[] = [];
  for (const path of markdown) {
    const source = readFileSync(join(root, path), "utf8");
    const regions = markdownProse(source);
    findings.push(...scan(path, source, regions, "spelling"));
    if (!GENERATED.test(source) && bannedTermsApply(path))
      findings.push(...scan(path, source, regions, "banned-term"));
  }
  for (const path of cli) {
    const source = readFileSync(join(root, path), "utf8");
    const { strings, messages } = cliStrings(path, source);
    findings.push(...scan(path, source, strings, "spelling"));
    findings.push(...scan(path, source, messages, "banned-term"));
  }
  findings.push(...catalogFindings(root));
  return findings.sort(
    (left, right) =>
      left.file.localeCompare(right.file) || left.line - right.line || left.column - right.column,
  );
}

/**
 * Pages written for contributors describe the release process in its own terms.
 * @param path - Repository-relative path.
 * @returns Whether the banned-term rule applies.
 */
function bannedTermsApply(path: string): boolean {
  return path !== "CONTRIBUTING.md" && path !== "WRITING.md" && path !== "CHANGELOG.md";
}

/**
 * Finds prose in Markdown or MDX: everything except front-matter keys, code blocks, inline code,
 * MDX comments, JSX tags and link targets.
 * @param source - Page source.
 * @returns Prose regions with their offsets.
 */
export function markdownProse(source: string): Region[] {
  const masked = source
    .replace(/^(?:```|~~~)[\s\S]*?^(?:```|~~~)[^\n]*$/gmu, blank)
    .replace(/\{\/\*[\s\S]*?\*\/\}/gu, blank)
    .replace(/<include\b[\s\S]*?<\/include>/gu, blank)
    .replace(/`[^`\n]*`/gu, blank)
    .replace(/<\/?[A-Za-z][^>]*>/gu, blank)
    .replace(/\]\([^)]*\)/gu, blank)
    .replace(/https?:\/\/\S+/gu, blank);
  return [{ text: masked, offset: 0 }];
}

/**
 * Collects string literals from a CLI source file. Every string counts for spelling; help text,
 * prompts and `fail()` messages also count for banned terms.
 * @param path - File path, used to recognize help files.
 * @param source - File source.
 * @returns String regions for each rule.
 */
export function cliStrings(
  path: string,
  source: string,
): { readonly strings: Region[]; readonly messages: Region[] } {
  const file = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
  const strings: Region[] = [];
  const messages: Region[] = [];
  const help = /\/cli-help[^/]*\.ts$/u.test(path);
  const visit = (node: ts.Node, message: boolean): void => {
    const text = literalText(node);
    if (text !== undefined) {
      const region = { text, offset: node.getStart(file) + 1 };
      strings.push(region);
      if (message || help) messages.push(region);
      return;
    }
    ts.forEachChild(node, (child) => visit(child, message || isMessageArgument(node, child)));
  };
  visit(file, false);
  return { strings, messages };
}

function literalText(node: ts.Node): string | undefined {
  if (
    ts.isStringLiteral(node) ||
    ts.isNoSubstitutionTemplateLiteral(node) ||
    ts.isTemplateHead(node) ||
    ts.isTemplateMiddle(node) ||
    ts.isTemplateTail(node)
  )
    return node.text;
  return undefined;
}

/**
 * Recognizes the message argument of `fail(code, message)` and text passed to prompt helpers.
 * @param parent - Possible call expression.
 * @param child - Child being visited.
 * @returns Whether the child is a user-facing message.
 */
function isMessageArgument(parent: ts.Node, child: ts.Node): boolean {
  if (!ts.isCallExpression(parent)) return false;
  const callee = parent.expression;
  const name = ts.isIdentifier(callee)
    ? callee.text
    : ts.isPropertyAccessExpression(callee)
      ? `${ts.isIdentifier(callee.expression) ? callee.expression.text : ""}.${callee.name.text}`
      : "";
  if (name === "fail") return parent.arguments[1] === child;
  return name.startsWith("prompt.") && parent.arguments.includes(child as ts.Expression);
}

/**
 * Checks the error-code catalog's titles, causes and next steps, read from its source files.
 * @param root - Repository root. @returns Findings located in the catalog files.
 */
function catalogFindings(root: string): UserTextFinding[] {
  const findings: UserTextFinding[] = [];
  const codes = "packages/relkit/src/diagnostics/codes/*.ts";
  for (const path of new Bun.Glob(codes).scanSync({ cwd: root })) {
    const source = readFileSync(join(root, path), "utf8");
    const file = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
    const regions: Region[] = [];
    const visit = (node: ts.Node): void => {
      if (
        ts.isPropertyAssignment(node) &&
        ts.isIdentifier(node.name) &&
        ["title", "happened", "fix"].includes(node.name.text)
      ) {
        const text = literalText(node.initializer);
        if (text !== undefined)
          regions.push({
            text: text.replace(/`[^`]*`/gu, blank),
            offset: node.initializer.getStart(file) + 1,
          });
      }
      ts.forEachChild(node, visit);
    };
    visit(file);
    findings.push(...scan(path, source, regions, "spelling"));
    findings.push(...scan(path, source, regions, "banned-term"));
  }
  return findings;
}

function scan(
  file: string,
  source: string,
  regions: readonly Region[],
  rule: UserTextFinding["rule"],
): UserTextFinding[] {
  const findings: UserTextFinding[] = [];
  for (const region of regions) {
    const text = region.text.replace(NAMESPACE, blank);
    for (const match of text.matchAll(rule === "spelling" ? SPELLING : BANNED)) {
      const position = locate(source, region.offset + (match.index ?? 0));
      findings.push({ file, ...position, rule, text: match[0] });
    }
  }
  return findings;
}

function locate(source: string, offset: number): { line: number; column: number } {
  const before = source.slice(0, offset);
  const line = before.split("\n").length;
  return { line, column: offset - before.lastIndexOf("\n") };
}

/** Replaces text with spaces of the same length, keeping line breaks and offsets. */
function blank(text: string): string {
  return text.replace(/[^\n]/gu, " ");
}

/**
 * Formats one finding as `file:line:column message`.
 * @param finding - Finding to format.
 * @returns One terminal line.
 */
export function formatFinding(finding: UserTextFinding): string {
  const message =
    finding.rule === "spelling"
      ? `write "RelKit", not "${finding.text}"`
      : `"${finding.text}" is an internal term; see WRITING.md for plain alternatives`;
  return `${finding.file}:${finding.line}:${finding.column} [${finding.rule}] ${message}`;
}

if (import.meta.main) {
  const root = process.argv[2] ?? join(import.meta.dir, "..");
  const findings = checkUserText(root);
  for (const finding of findings) console.error(formatFinding(finding));
  if (findings.length > 0) {
    console.error(`User-facing text check failed with ${findings.length} finding(s).`);
    process.exit(1);
  }
  console.log(`User-facing text check passed (${relative(process.cwd(), root) || "."}).`);
}
