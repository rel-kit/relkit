/**
 * Renders the metrics report as the table on the docs metrics page (`/docs/metrics`) and as the
 * Markdown summary CI writes to a job summary. Pure apart from reading the one report file.
 */
import { existsSync, readFileSync } from "node:fs";
import type { MetricsReport, MetricStatus } from "./types.js";

const LABELS: Record<MetricStatus, string> = {
  met: "Met",
  "not-met": "Not met",
  "no-data": "No data",
};

/**
 * Reads a metrics report.
 * @param path - Path of `metrics.json`.
 * @returns The report.
 */
export function readMetricsReport(path: string): MetricsReport {
  const report = JSON.parse(readFileSync(path, "utf8")) as MetricsReport;
  if (report.protocol !== "relkit.metrics") throw new Error(`${path} is not a metrics report.`);
  return report;
}

/**
 * Selects the report the docs build renders: the file named by `RELKIT_METRICS_REPORT` when it
 * exists (CI sets it to the report its run just produced), otherwise the checked-in fallback.
 * @param fallback - Path of the checked-in `apps/docs/data/metrics.json`.
 * @param environment - Process environment.
 * @returns The path and whether it is the CI report.
 */
export function metricsReportPath(
  fallback: string,
  environment: Readonly<Record<string, string | undefined>> = process.env,
): { readonly path: string; readonly source: "ci" | "fallback" } {
  const ci = environment.RELKIT_METRICS_REPORT;
  return ci !== undefined && ci !== "" && existsSync(ci)
    ? { path: ci, source: "ci" }
    : { path: fallback, source: "fallback" };
}

function cell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

/**
 * Renders the metrics table.
 * @param report - Metrics report.
 * @returns Markdown with one row per metric and a line saying when and where it was measured.
 */
export function metricsMarkdown(report: MetricsReport): string {
  const rows = report.metrics.map(
    (metric) =>
      `| ${cell(metric.name)} | ${cell(metric.value)} | ${cell(metric.target)} | ${LABELS[metric.status]} | ${cell(metric.detail)} |`,
  );
  const missing = report.metrics.filter((metric) => metric.status === "no-data").length;
  return `| Metric | Current | Target | Status | Source |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

Measured ${report.createdAt.slice(0, 10)}${report.commit ? ` at commit \`${report.commit.slice(0, 12)}\`` : ""}. ${
    missing === 0
      ? "Every metric has data."
      : `${missing} of ${report.metrics.length} metrics show "no data" because their CI output was not available to this run.`
  }
`;
}

/**
 * Renders the docs snippet.
 * @param fallback - Path of the checked-in report.
 * @returns MDX for `_snippets/generated/metrics.mdx`.
 */
export function metricsSnippet(fallback: string): string {
  const { path, source } = metricsReportPath(fallback);
  const origin = source === "ci" ? "the metrics report of the CI run" : "data/metrics.json";
  return `{/* Generated by apps/docs/scripts/generate.ts from ${origin}. Do not edit. */}

${metricsMarkdown(readMetricsReport(path))}`;
}
