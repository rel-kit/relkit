/** Keeps every scaffold command reachable through authored instructions and generated command options. */
import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { getCliHelpModel } from "@relkit/cli/help";
import { guideRelations } from "../scripts/guide-catalog.js";

test("every add command has a guide and complete CLI reference without inline option tables", async () => {
  const content = resolve(import.meta.dir, "../content");
  const model = getCliHelpModel("test");
  const add = model.commands.find(({ name }) => name === "add")!;
  const pages = guideRelations.map(({ path }) =>
    readFileSync(resolve(content, `${path}.mdx`), "utf8"),
  );
  const index = readFileSync(resolve(content, "docs/modules/cli/add-artifacts.mdx"), "utf8");
  const reference = readFileSync(resolve(content, "docs/api/cli.mdx"), "utf8");
  for (const command of add.commands) {
    const fragment = `add-${command.name}-options.mdx`;
    const guides = pages.filter((source) => source.includes(`bun run relkit add ${command.name} `));
    expect(guides.length, command.name).toBeGreaterThan(0);
    expect(guides.every((source) => !source.includes(`/_snippets/generated/${fragment}`))).toBe(
      true,
    );
    expect(index).toContain(`relkit add ${command.name}`);
    expect(reference).toContain(`relkit add ${command.name}`);
    const row = index.split("\n").find((line) => line.includes(`\`relkit add ${command.name}`));
    const destination = row?.match(/\]\((\/docs\/(?:learn|modules)\/[^)#]+)(?:#[^)]+)?\)/)?.[1];
    expect(
      destination,
      `${command.name}: link to its Learn or Modules creation page`,
    ).toBeDefined();
    const page = readFileSync(resolve(content, `${destination!.slice(1)}.mdx`), "utf8");
    const example = [...page.matchAll(/<include\b[^>]*\bsource="([^"]+)"/g)].find((match) => {
      if (command.name === "job") return match[1]!.includes("/jobs/");
      if (command.name === "transform") return match[1]!.includes("/transforms/");
      return true;
    });
    const scaffold = page.indexOf(`bun run relkit add ${command.name} `);
    expect(
      scaffold,
      `${command.name}: command is present at its linked destination`,
    ).toBeGreaterThan(-1);
    expect(example, `${command.name}: maintained source example follows the command`).toBeDefined();
    expect(scaffold, `${command.name}: scaffold before its source example`).toBeLessThan(
      example!.index!,
    );
    expect(page).toContain(`/docs/api/cli#relkit-add-${command.name}`);
    const options = readFileSync(resolve(content, `_snippets/generated/${fragment}`), "utf8");
    expect(options).toContain("Generated by apps/docs/scripts/generate.ts");
    for (const option of [...model.options, ...command.options])
      expect(options, `${command.name}: --${option.name}`).toContain(`--${option.name}`);
  }
});
