/** Protects read-only freshness checks and authored files from stale-output cleanup. */
import { expect, test } from "bun:test";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pruneGenerated } from "../scripts/generation-files.js";

test("reports obsolete MDX during a check without deleting it or authored neighbors", async () => {
  const root = await mkdtemp(join(tmpdir(), "relkit-docs-freshness-"));
  try {
    const stale = join(root, "obsolete.mdx");
    const authored = join(root, "index.mdx");
    const bytes = "{/* Generated by apps/docs/scripts/generate.ts. Do not edit. */}\nold";
    await writeFile(stale, bytes);
    await writeFile(authored, "Authored introduction");
    await expect(pruneGenerated(root, new Set(), true)).rejects.toThrow("obsolete.mdx");
    expect(await readFile(stale, "utf8")).toBe(bytes);
    await pruneGenerated(root, new Set(), false);
    expect(await Bun.file(stale).exists()).toBe(false);
    expect(await readFile(authored, "utf8")).toBe("Authored introduction");
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
