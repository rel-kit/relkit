/** Verifies published documentation against maintained source, layout and catalogs. */
import { expect, test } from "bun:test";
import { readFile, readdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { apiPackageDefinitions } from "../scripts/documentation-catalog.js";
import { exampleDefinitions, primaryCapabilities } from "../components/landing/data.js";
import {
  renderCapabilities,
  renderCommandOptions,
  renderRelated,
} from "../scripts/generate-guides.js";
import { guideGroups, guideRelations } from "../scripts/guide-catalog.js";
import { markdownFiles } from "./documentation-fixture.js";
const content = resolve(import.meta.dir, "../content/docs");

test("publishes authored, CLI, and application-facing API documentation", async () => {
  const files = await markdownFiles(content);
  expect(files.length).toBeGreaterThanOrEqual(34);
  expect(await readFile(resolve(content, "operations/cli-reference.mdx"), "utf8")).toContain(
    "`relkit graph diff <before> <after>`",
  );
  for (const { group, packageName, slug } of apiPackageDefinitions) {
    const reference = await readFile(resolve(content, `api/${slug}.mdx`), "utf8");
    expect(reference).toContain("Generated by apps/docs/scripts/generate.ts");
    expect(reference).toContain(packageName);
    if (group === "core") expect(reference).toContain("**Signature**");
  }
});

test("leads with the five product concepts and separates guides from API reference", async () => {
  expect(exampleDefinitions.map(({ title }) => title)).toEqual([
    "Service",
    "Routes",
    "Functions",
    "Events",
    "Observability",
  ]);
  expect(primaryCapabilities.map(({ title }) => title)).toEqual(
    exampleDefinitions.map(({ title }) => title),
  );
  const landingSources = exampleDefinitions.map(({ source }) => source);
  for (const removed of [
    "apps/docs/examples/landing/define-app.ts",
    "apps/docs/examples/landing/local-redis.ts",
    "apps/docs/examples/landing/aws-s3.ts",
  ])
    expect(landingSources).not.toContain(removed);

  expect(await Bun.file(resolve(content, "api/meta.json")).json()).toMatchObject({
    title: "API Reference",
    pages: expect.arrayContaining(["app", "integrations"]),
  });
  expect(await Bun.file(resolve(content, "api/integrations/meta.json")).json()).toMatchObject({
    title: "Integrations",
    pages: expect.arrayContaining(["docker", "redis", "s3", "sentry", "otlp"]),
  });
});

test("keeps Core concepts near Start and retires the duplicate Async section", async () => {
  expect(guideGroups.map(({ directory }) => directory).slice(0, 3)).toEqual([
    "start",
    "fundamentals",
    "service",
  ]);
  expect(guideGroups.find(({ directory }) => directory === "fundamentals")).toMatchObject({
    title: "Core concepts",
    pages: ["index", "application", "functions", "schemas", "errors", "context", "environment"],
  });
  expect(guideGroups.find(({ directory }) => directory === "operations")).toMatchObject({
    title: "Operations",
    pages: [
      "index",
      "observability",
      "inspector",
      "realtime-agents-streaming",
      "testing",
      "deployment",
      "troubleshooting",
      "cli-reference",
    ],
  });
  expect(guideGroups.some(({ directory }) => directory === "async")).toBe(false);

  const redirects = await readFile(resolve(import.meta.dir, "../next.config.mjs"), "utf8");
  for (const [source, destination] of [
    ["events", "/docs/events"],
    ["listeners", "/docs/events/consume"],
    ["jobs", "/docs/jobs"],
    ["schedules", "/docs/jobs/schedules"],
  ]) {
    expect(redirects).toContain(`["/docs/async/${source}", "${destination}"]`);
  }
});

test("documents current Docker-backed service versions from integration source", async () => {
  const guide = await readFile(resolve(content, "integrations/local-docker.mdx"), "utf8");
  for (const source of [
    "integrations/packages/redis/src/local-recipe/index.ts",
    "integrations/packages/s3/src/local-recipe/index.ts",
  ]) {
    const recipe = await readFile(resolve(import.meta.dir, "../../..", source), "utf8");
    const image = recipe.match(/"([^\"]+@sha256:[a-f0-9]{64})"/)?.[1];
    expect(image).toBeDefined();
    if (!image) throw new Error("Recipe has no pinned image");
    const [tag, digest] = image.split("@");
    if (!tag || !digest) throw new Error("Recipe has an invalid image");
    expect(guide).toContain(tag);
    expect(guide).toContain(digest);
  }
});
