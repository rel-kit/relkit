/** Every code package source can emit has a catalog entry and a generated docs page. */
import { afterAll, expect, test } from "bun:test";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { DIAGNOSTIC_CODES } from "relkit/diagnostics/codes";
import {
  emittedCodes,
  generateErrorPages,
  renderErrorPage,
  undocumentedCodes,
} from "../scripts/generate-error-pages.js";

const root = resolve(import.meta.dir, "../../..");
const fixture = await mkdtemp(join(tmpdir(), "relkit-error-pages-"));
afterAll(() => rm(fixture, { recursive: true, force: true }));

test("every code in package source is documented", () => {
  const emitted = emittedCodes(root);
  expect(emitted.size).toBeGreaterThan(400);
  expect(emitted.has("RELKIT_ENV")).toBe(false);
  expect(emitted.get("RELKIT_SCHEMA_UNAVAILABLE")).toContain("relkit/schema");
  expect(undocumentedCodes(emitted)).toEqual([]);
});

test("generation fails and names a code that has no entry", async () => {
  await mkdir(join(fixture, "packages/orders/src"), { recursive: true });
  await mkdir(join(fixture, "packages/orders/tests"), { recursive: true });
  await writeFile(join(fixture, "packages/orders/package.json"), '{"name":"@relkit/orders"}');
  await writeFile(
    join(fixture, "packages/orders/src/fail.ts"),
    'throw fail("RELKIT_ORDER_NEW_THING", "x"); const env = process.env["RELKIT_ENV"];\n',
  );
  await writeFile(join(fixture, "packages/orders/tests/a.test.ts"), '"RELKIT_ONLY_IN_TESTS";\n');
  const written: string[] = [];
  const emit = async (path: string) => void written.push(path);
  await expect(generateErrorPages(fixture, fixture, emit, [])).rejects.toThrow(
    /no docs page:\nRELKIT_ORDER_NEW_THING\n/u,
  );
  expect(written).toEqual([]);
});

test("a page states what happened, the next step and who reports it", () => {
  const entry = DIAGNOSTIC_CODES.find(({ code }) => code === "RELKIT_DEV_USAGE")!;
  const page = renderErrorPage(entry, new Map([[entry.code, ["@relkit/cli"]]]));
  expect(page).toContain("title: RELKIT_DEV_USAGE");
  expect(page).toContain(`## What happened\n\n${entry.happened}`);
  expect(page).toContain("## What to do");
  expect(page).toContain("Reported by `@relkit/cli`.");
  expect(page).toContain("Generated by apps/docs/scripts/generate.ts. Do not edit.");
});
