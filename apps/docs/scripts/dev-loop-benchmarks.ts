/**
 * Renders the benchmarks page's tables from a development-loop benchmark report. The
 * report is the file named by `RELKIT_DEV_LOOP_REPORT` when it exists, which release
 * readiness sets to the report its pull request run just produced; otherwise the
 * checked-in `data/dev-loop-benchmarks.json`, a local run kept as the fallback. Pure apart
 * from reading that one file.
 */
import { existsSync, readFileSync } from "node:fs";
import { resolve, sep } from "node:path";

/** Fields of the report (`scripts/dev-loop-benchmark/benchmark.types.ts`) the page shows. */
interface Report {
  readonly createdAt: string;
  readonly commit?: string;
  readonly host: {
    readonly bun: string;
    readonly platform: string;
    readonly arch: string;
    readonly os: string;
    readonly cpu?: string;
    readonly cpus: number;
    readonly memoryBytes: number;
    readonly runner: string;
  };
  readonly sizes: readonly {
    readonly functions: number;
    readonly reload: {
      readonly p95Ms: number;
      readonly medianMs: number;
      readonly firstStartMs: number;
    };
    readonly check: { readonly peakBytes: number };
    readonly tsc: { readonly peakBytes: number };
    readonly memoryRatio: number;
  }[];
  readonly budgets: readonly {
    readonly functions: number;
    readonly reloadP95Ms: number;
    readonly memoryRatio: number;
  }[];
  readonly passed: boolean;
}

/**
 * Selects the report the docs build renders. The CI report is read only from inside the
 * repository (release readiness writes it under the workspace), so the variable cannot name
 * a file elsewhere.
 * @param docsRoot - `apps/docs`.
 * @param environment - Process environment.
 * @returns Report path and whether it is the CI report.
 */
export function benchmarkReportPath(
  docsRoot: string,
  environment: Readonly<Record<string, string | undefined>> = process.env,
): { readonly path: string; readonly source: "ci" | "fallback" } {
  const ci = ciReportPath(resolve(docsRoot, "..", ".."), environment.RELKIT_DEV_LOOP_REPORT);
  if (ci !== undefined) return { path: ci, source: "ci" };
  return { path: resolve(docsRoot, "data/dev-loop-benchmarks.json"), source: "fallback" };
}

/**
 * Resolves the CI report path when it names an existing file inside the repository.
 * @param repositoryRoot - Absolute repository root.
 * @param value - `RELKIT_DEV_LOOP_REPORT`.
 * @returns The absolute path, or undefined when unset, outside the repository or missing.
 */
function ciReportPath(repositoryRoot: string, value: string | undefined): string | undefined {
  if (value === undefined || value === "") return undefined;
  const candidate = resolve(repositoryRoot, value);
  if (!candidate.startsWith(repositoryRoot + sep)) return undefined;
  return existsSync(candidate) ? candidate : undefined;
}

/**
 * Renders the tables.
 * @param docsRoot - `apps/docs`.
 * @returns MDX for `_snippets/generated/dev-loop-benchmarks.mdx`.
 */
export function devLoopBenchmarks(docsRoot: string): string {
  const { path, source } = benchmarkReportPath(docsRoot);
  const report = JSON.parse(readFileSync(path, "utf8")) as Report;
  const mib = (bytes: number) => `${(bytes / 1_048_576).toFixed(0)} MiB`;
  const rows = report.sizes.map((size) => {
    const budget = report.budgets.find((entry) => entry.functions === size.functions);
    return `| ${size.functions} | ${size.reload.p95Ms.toFixed(0)} ms | ${budget ? `< ${budget.reloadP95Ms} ms` : "—"} | ${mib(size.check.peakBytes)} | ${mib(size.tsc.peakBytes)} | ${size.memoryRatio.toFixed(2)}× | ${budget ? `≤ ${budget.memoryRatio}×` : "—"} |`;
  });
  const host = report.host;
  return `{/* Generated by apps/docs/scripts/generate.ts from ${source === "ci" ? "the release-readiness benchmark report" : "data/dev-loop-benchmarks.json"}. Do not edit. */}

| Functions | Reload p95 | Budget | \`relkit check\` peak | \`tsc\` peak | Ratio | Budget |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

Measured ${report.createdAt.slice(0, 10)}${report.commit ? ` at commit \`${report.commit.slice(0, 12)}\`` : ""} on ${host.runner === "local" ? "a local machine" : host.runner}:
${host.cpu ?? "unknown CPU"} (${host.cpus} cores, ${mib(host.memoryBytes)}), ${host.platform} ${host.os} ${host.arch}, Bun ${host.bun}.
${report.passed ? "Every budget held on this run." : "This run missed at least one budget; release readiness fails until it holds."}
`;
}
