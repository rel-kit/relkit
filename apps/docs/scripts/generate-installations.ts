/**
 * Emits reusable installation instructions from selected owner metadata. The
 * existing generator owns formatting, freshness checks and output files; this
 * producer resolves commands and application-owned repairs without SDK startup.
 */
import { buildCatalogDependency, buildCatalogPatch } from "create-relkit/internal/build-catalog";
import { resolveCatalogVersion } from "create-relkit/catalog-resolution";
import { Effect } from "effect";
import { installationDeclarations, loadInstallationCatalog } from "./installation-catalog.js";
import type { InstallationCatalog, InstallationRecipe } from "./installation-catalog.types.js";
import { installationRecipes } from "./installation-recipes.js";

/** Emits all selected recipes through the documentation generator's file boundary.
 * @param root - Checkout owning the release metadata.
 * @param emit - Existing formatted writer/checker, relative to content.
 * @returns Completion after every selected fragment is written or checked.
 */
export async function generateInstallations(
  root: string,
  emit: (path: string, value: string) => Promise<void>,
): Promise<void> {
  const catalog = await loadInstallationCatalog(root);
  await emit("_snippets/generated/installations/native-drivers.mdx", renderNativeDrivers(catalog));
  await Effect.runPromise(
    Effect.forEach(
      Object.entries(installationRecipes),
      ([name, recipe]) =>
        Effect.tryPromise(() =>
          emit(
            `_snippets/generated/installations/${name}.mdx`,
            renderInstallation(recipe, catalog),
          ),
        ),
      { concurrency: 4, discard: true },
    ),
  );
}

/** Renders commands from one recipe without maintaining another version table.
 * @param recipe - Reader-selected packages, capabilities and tooling.
 * @param catalog - Validated metadata snapshot.
 * @returns MDX with runtime/development commands and selected repairs in order.
 */
export function renderInstallation(
  recipe: InstallationRecipe,
  catalog: InstallationCatalog,
): string {
  const declarations = installationDeclarations(recipe, catalog);
  const parts = ["{/* Generated by apps/docs/scripts/generate.ts. Do not edit. */}"];
  if (recipe.global) {
    parts.push(
      `Install the standalone tool with Bun 1.3.10 or newer. Tool installation does not enable application inspection.\n\n${shell([command("bun add --global", declarations.dependencies)])}`,
    );
    return parts.join("\n\n");
  }
  if (recipe.betterFetch) {
    const overrides = { "@better-fetch/fetch": buildCatalogDependency("@better-fetch/fetch") };
    parts.push(
      `Before installing, merge these selected declaration repairs into the existing package manifest, preserving unrelated overrides:\n\n${json({ overrides, pnpm: { overrides } })}`,
    );
  }
  parts.push(
    `From this guide's application/package root, install only its selected requirements:\n\n${shell([command("bun add", declarations.dependencies), command("bun add --dev", declarations.devDependencies)].filter(Boolean))}`,
  );
  if (recipe.drizzlePatch) parts.push(drizzleRepair());
  parts.push(
    "Keep these owner-specific versions and the lockfile together. Runtime SDKs belong in `dependencies`; build/type tooling belongs in `devDependencies`. Installing an adapter does not supply its optional SDK peers or enable the feature's configuration.",
  );
  return `${parts.join("\n\n")}\n`;
}

/** Renders the release-owned Drizzle asset and its application-level registration.
 * @returns Ordered copy, manifest merge and reinstall instructions.
 */
function drizzleRepair(): string {
  const patch = buildCatalogPatch("drizzle-orm");
  const path = `patches/${patch.key}.patch`;
  return `The selected Drizzle version also needs the release's declaration repair. The development-only \`create-relkit\` package supplies its exact asset; a dependency cannot register Bun patches for its consumer.\n\n${shell(["mkdir -p patches", `cp node_modules/create-relkit/dist/${patch.asset} ${quote(path)}`])}\n\nMerge this entry into the application's existing \`patchedDependencies\`, preserving other patches. Keep the asset in source control:\n\n${json({ patchedDependencies: { [patch.key]: path } })}\n\nThen apply the registered repair before check/typecheck:\n\n${shell(["bun install"])}`;
}

/** Lists only the separately installed native checkpoint/store drivers tested by their owner.
 * @param catalog - Decoded LangChain manifest and catalog snapshot.
 * @returns A choice table; these alternatives are never installed as one broad cohort.
 */
function renderNativeDrivers(catalog: InstallationCatalog): string {
  const owner = catalog.packages.get("@relkit/langchain");
  const rows = ["sqlite", "postgres", "mongodb", "redis"].map((driver) => {
    const name = `@langchain/langgraph-checkpoint-${driver}`;
    const version = resolveCatalogVersion(
      { ...catalog.workspace },
      name,
      owner?.devDependencies?.[name],
    );
    return `| ${driver} | ${quote(`${name}@${version}`)} | \`bun add ${quote(`${name}@${version}`)}\` |`;
  });
  return `{/* Generated by apps/docs/scripts/generate.ts. Do not edit. */}\n\n| Driver | Tested package | Install only your selected driver |\n| --- | --- | --- |\n${rows.join("\n")}\n`;
}

/** Renders a deterministic install command, quoting shell-significant ranges.
 * @param prefix - Fixed Bun command and selected manifest-section flag.
 * @param declarations - Package/version declarations selected by owner metadata.
 * @returns One shell line, or empty when this section has no requirements.
 */
function command(prefix: string, declarations: Readonly<Record<string, string>>): string {
  const packages = Object.entries(declarations).sort(([left], [right]) =>
    left.localeCompare(right),
  );
  return packages.length === 0
    ? ""
    : `${prefix} ${packages.map(([name, version]) => quote(`${name}@${version}`)).join(" ")}`;
}

/** Keeps plain package specs readable while protecting shell-significant range operators.
 * @param value - Package declaration or owned patch path.
 * @returns A plain shell word, or a POSIX single-quoted argument when escaping is needed.
 */
function quote(value: string): string {
  if (/^[A-Za-z0-9@/._+-]+$/.test(value)) return value;
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/** Formats command lines as a runnable shell block.
 * @param lines - Nonempty ordered command lines.
 * @returns A fenced shell block for MDX inclusion.
 */
function shell(lines: readonly string[]): string {
  return `\`\`\`sh\n${lines.join("\n")}\n\`\`\``;
}

/** Formats only fields that the reader merges into their own manifest.
 * @param value - Selected repair/override fields.
 * @returns A fenced JSON merge example.
 */
function json(
  value: Readonly<
    Record<
      string,
      Readonly<Record<string, string>> | { readonly overrides: Readonly<Record<string, string>> }
    >
  >,
): string {
  return `\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``;
}
