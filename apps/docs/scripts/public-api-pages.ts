/** Renders exhaustive import/symbol discovery from export maps and exact native contracts. */
import { apiPackageDefinitions } from "./documentation-catalog.js";
import { referenceExample } from "./api-related.js";
import { symbolContract } from "./public-api-contracts.js";
import type { PublicImport, PublicSymbol, SymbolContract } from "./public-api.types.js";

/** Lists every supported import, then links each exported name to its original contract.
 * @param entries - Import paths of one supported package. @param contracts - Resolved native contracts.
 * @returns Shared Markdown for rendering and copying. */
export function publicExports(
  entries: readonly PublicImport[],
  contracts: ReadonlyMap<string, SymbolContract>,
): string {
  const paths = entries
    .map(({ specifier, symbols }) => `- \`${specifier}\` — ${symbols.length} exports`)
    .join("\n");
  const definition = apiPackageDefinitions.find(
    ({ packageName }) => packageName === entries[0]?.packageName,
  );
  if (!definition) throw new Error("Cannot render exports without a supported package");
  const usage = referenceExample(definition.slug);
  const names = new Map<
    string,
    { name: string; value: boolean; href: string; imports: string[]; example: string }
  >();
  for (const entry of entries)
    for (const symbol of entry.symbols) {
      const contract = symbolContract(entry, symbol, contracts);
      if (!contract) throw new Error(`Undocumented public API: ${entry.specifier}.${symbol.name}`);
      const key = `${symbol.name}:${contract.href}`;
      const row = names.get(key) ?? {
        name: symbol.name,
        value: symbol.value,
        href: contract.href,
        imports: [],
        example: exampleLink(symbol, contract, usage),
      };
      row.imports.push(entry.specifier);
      names.set(key, row);
    }
  if (names.size === 0)
    return `## Public imports\n\n${paths}\n\nThis package contains integration metadata. Its JavaScript entrypoint exports no runtime APIs; install each selected integration separately.\n`;
  const rows = [...names.values()]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(
      (row) =>
        `| [${row.name}](${row.href}) | ${row.value ? "Value" : "Type"} | ${row.imports.map((name) => `\`${name}\``).join(", ")} | ${row.example} |`,
    );
  return `## Public imports\n\n${paths}\n\n## All exported APIs\n\nNames link to their complete contracts. Re-exports share their original contract; legacy exports keep their separate identity. Examples link to the API's inline sample, a maintained repository usage, or the shared module walkthrough.\n\n| API | Kind | Import from | Example |\n| --- | --- | --- | --- |\n${rows.join("\n")}\n`;
}

/** Prefers the API's own sample, then an imported usage, then its shared module walkthrough.
 * @param symbol - Source example evidence. @param contract - Native contract and inline sample availability.
 * @param usage - Authored usage page. @returns A labeled Markdown link that states which kind of example it opens. */
function exampleLink(symbol: PublicSymbol, contract: SymbolContract, usage: string): string {
  if (contract.example) return `[API example](${contract.href})`;
  if (symbol.exampleSource)
    return `[Source example](https://github.com/rel-kit/relkit/blob/main/${symbol.exampleSource})`;
  return `[Module example](${usage})`;
}

/** Creates the public package directory, including the documented disposition of internal exports.
 * @param inventory - Complete manifest inventory. @returns Generated orientation page. */
export function publicDirectory(inventory: readonly PublicImport[]): string {
  const supported = inventory.filter(({ internal }) => !internal);
  const symbols = new Set(
    supported.flatMap(({ symbols }) =>
      symbols.map(({ source, original }) => `${source}:${original}`),
    ),
  );
  const rows = apiPackageDefinitions.map(({ slug, title, packageName }) => {
    const entries = supported.filter((entry) => entry.packageName === packageName);
    return `| [${title}](/docs/api/${slug}#public-imports) | ${entries.map(({ specifier }) => `\`${specifier}\``).join(", ")} | [Usage and examples](${referenceExample(slug)}) |`;
  });
  const internal = [
    ...new Set(
      inventory
        .filter(({ internal }) => internal)
        .map(({ packageName, specifier }) =>
          supported.some((entry) => entry.packageName === packageName) ? specifier : packageName,
        ),
    ),
  ].sort();
  return `---\ntitle: All public APIs\ndescription: Every supported RELKIT package, import path and exported API, with module examples and complete contracts.\nsearch:\n  exclude: true\nsidebar:\n  icon: list-tree\n---\n\n{/* Generated by apps/docs/scripts/generate.ts. Do not edit. */}\n\nFind a package below, then use its **All exported APIs** table to jump to any value or type.\n\nThe export-map audit covers **${apiPackageDefinitions.length} supported packages**, **${supported.length} import paths**, and **${symbols.size} distinct declarations**. Aliases point to the same declaration.\n\n| Reference | Supported imports | Start here |\n| --- | --- | --- |\n${rows.join("\n")}\n\n## Internal packages and subpaths\n\nThe following packages are explicitly described as internal or empty compatibility packages, or use an \`/internal\` export path. They are inventoried but are not supported application imports. Public re-exports from their implementation files are documented through the supported facade above.\n\n${internal.map((name) => `- \`${name}\``).join("\n")}\n`;
}
