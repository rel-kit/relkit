/**
 * Generates one docs page per `RELKIT_*` code from the diagnostics catalog, and fails when package
 * source can emit a code that has no catalog entry.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
  DIAGNOSTIC_CODES,
  RELKIT_NON_CODE_NAMES,
  diagnosticDocsPath,
  diagnosticSlug,
  type DiagnosticCodeEntry,
} from "relkit/diagnostics/codes";
import type { Emit } from "./generation.types.js";

const SOURCES = ["packages/*/src/**/*.{ts,tsx}", "integrations/packages/*/src/**/*.{ts,tsx}"];
const LITERAL = /(["'`])(RELKIT_[A-Z0-9_]+)\1/gu;

/**
 * Finds every code literal in package source, with the packages that emit it.
 * @param root - Repository root.
 * @returns Code to sorted package names; environment variables and markers are left out.
 */
export function emittedCodes(root: string): Map<string, string[]> {
  const codes = new Map<string, Set<string>>();
  for (const pattern of SOURCES) {
    for (const path of new Bun.Glob(pattern).scanSync({ cwd: root })) {
      if (/(?:^|\/)(?:tests?|__tests__)\/|\.(?:test|spec)\.tsx?$|\.d\.ts$/u.test(path)) continue;
      const source = readFileSync(join(root, path), "utf8");
      for (const match of source.matchAll(LITERAL)) {
        const code = match[2]!;
        if (RELKIT_NON_CODE_NAMES.has(code)) continue;
        const owners = codes.get(code) ?? new Set<string>();
        owners.add(packageName(root, path));
        codes.set(code, owners);
      }
    }
  }
  return new Map([...codes].map(([code, owners]) => [code, [...owners].sort()]));
}

/**
 * Lists emitted codes with no catalog entry.
 * @param emitted - Codes found in source.
 * @param catalog - Catalog entries.
 * @returns Missing codes, sorted.
 */
export function undocumentedCodes(
  emitted: ReadonlyMap<string, readonly string[]>,
  catalog: readonly DiagnosticCodeEntry[] = DIAGNOSTIC_CODES,
): string[] {
  const documented = new Set(catalog.map(({ code }) => code));
  return [...emitted.keys()].filter((code) => !documented.has(code as never)).sort();
}

/**
 * Writes the error pages and index, after checking every emitted code is documented.
 * @param root - Repository root.
 * @param content - Docs content directory.
 * @param emit - Generated-file writer.
 * @param catalog - Catalog entries, replaceable in tests.
 * @returns Completion; throws naming undocumented codes or missing hand-written pages.
 */
export async function generateErrorPages(
  root: string,
  content: string,
  emit: Emit,
  catalog: readonly DiagnosticCodeEntry[] = DIAGNOSTIC_CODES,
): Promise<void> {
  const emitted = emittedCodes(root);
  const missing = undocumentedCodes(emitted, catalog);
  if (missing.length > 0)
    throw new Error(
      `These codes have no entry in packages/relkit/src/diagnostics/codes, so they have no docs page:\n${missing.join("\n")}\nAdd an entry for each code; see WRITING.md.`,
    );
  const unwritten = catalog.filter(
    ({ page }) =>
      page !== undefined &&
      !existsSync(join(content, `${page.slice(1)}.mdx`)) &&
      !existsSync(join(content, page.slice(1), "index.mdx")),
  );
  if (unwritten.length > 0)
    throw new Error(
      `These codes name hand-written pages that do not exist:\n${unwritten.map(({ code, page }) => `${code}: ${page}`).join("\n")}`,
    );
  for (const entry of catalog) {
    if (entry.page !== undefined) continue;
    await emit(`docs/errors/${diagnosticSlug(entry.code)}.mdx`, renderErrorPage(entry, emitted));
  }
  await emit("docs/errors/index.mdx", renderErrorIndex(catalog));
}

/**
 * Renders one code's page.
 * @param entry - Catalog entry.
 * @param emitted - Packages that emit each code.
 * @returns MDX source.
 */
export function renderErrorPage(
  entry: DiagnosticCodeEntry,
  emitted: ReadonlyMap<string, readonly string[]>,
): string {
  const owners = emitted.get(entry.code) ?? [];
  return `---
title: ${entry.code}
description: ${JSON.stringify(`${entry.title}.`)}
pagination: false
search:
  keywords: [${entry.code}]
sidebar:
  icon: triangle-alert
---

{/* Generated by apps/docs/scripts/generate.ts. Do not edit. */}

**${mdx(entry.title)}.**

## What happened

${mdx(entry.happened)}

## What to do

${mdx(entry.fix)}
${owners.length > 0 ? `\nReported by ${owners.map((owner) => `\`${owner}\``).join(", ")}.\n` : ""}
See [all error codes](/docs/errors).
`;
}

/**
 * Renders the index of every code.
 * @param catalog - Catalog entries.
 * @returns MDX source.
 */
export function renderErrorIndex(catalog: readonly DiagnosticCodeEntry[]): string {
  const rows = [...catalog]
    .sort((left, right) => left.code.localeCompare(right.code))
    .map(
      (entry) =>
        `| [\`${entry.code}\`](${diagnosticDocsPath(entry.code)}) | ${mdx(entry.title).replaceAll("|", "\\|")} |`,
    );
  return `---
title: Error codes
description: Every RelKit error and warning code, what it means and what to do next.
sidebar:
  icon: triangle-alert
---

{/* Generated by apps/docs/scripts/generate.ts. Do not edit. */}

Every error and warning RelKit prints starts with a \`RELKIT_*\` code and ends with a link to that code's page. Each page says what happened and what to do next.

| Code | Problem |
| ---- | ------- |
${rows.join("\n")}
`;
}

/** Escapes MDX syntax outside inline code spans. */
function mdx(text: string): string {
  return text
    .split(/(`[^`]*`)/u)
    .map((part) => (part.startsWith("`") ? part : part.replace(/[{}<>]/gu, (c) => `\\${c}`)))
    .join("");
}

function packageName(root: string, path: string): string {
  const area = /^packages\/relkit\/src\/([^/]+)\//u.exec(path)?.[1];
  if (area !== undefined) return area === "app" ? "relkit" : `relkit/${area}`;
  const directory = path.startsWith("integrations/")
    ? path.split("/").slice(0, 3).join("/")
    : path.split("/").slice(0, 2).join("/");
  const manifest = join(root, directory, "package.json");
  if (!existsSync(manifest)) return dirname(directory);
  return (JSON.parse(readFileSync(manifest, "utf8")) as { name: string }).name;
}
