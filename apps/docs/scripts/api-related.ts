/** Connects generated contracts to the authored configuration and task owners. */
import { features } from "./feature-catalog.js";
import { guideRelations } from "./guide-catalog.js";
import { apiPackageDefinitions } from "./documentation-catalog.js";
import { frontendUsage } from "./client-guide-catalog.js";

/** Selects the authored usage page for a package, keeping examples with their module owner.
 * @param slug - Reference package route. @returns Existing Learn/module URL or a coverage failure. */
export function referenceExample(slug: string): string {
  const feature = features.find(({ apiPackage }) => apiPackage === slug);
  if (feature) return `/${feature.guide.replace(/\/index$/, "")}`;
  const relation = guideRelations.find(
    ({ path, api, examples }) =>
      path.startsWith("docs/modules/") && examples.length > 0 && api.some((name) => name === slug),
  );
  if (!relation) throw new Error(`Public package has no module examples: ${slug}`);
  return `/${relation.path.replace(/\/index$/, "")}`;
}

/** Renders contextual links without copying narrative prose into generated reference.
 * @param slug - API package route. @returns Module and task links for this package. */
export function referenceLinks(slug: string): string {
  const apis = authoringLinks(slug);
  const modules = features
    .filter(({ apiPackage }) => apiPackage === slug)
    .map(({ title, guide }) => `[${title}](/${guide.replace(/\/index$/, "")})`);
  for (const { path, api } of guideRelations) {
    if (path.startsWith("docs/modules/") && api.some((name) => name === slug))
      modules.push(
        `[${path
          .replace(/\/index$/, "")
          .split("/")
          .at(-1)!
          .replaceAll("-", " ")}](/${path.replace(/\/index$/, "")})`,
      );
  }
  const guides = guideRelations
    .filter(
      ({ path, api }) =>
        path.startsWith("guides/") && path !== "guides/index" && api.some((name) => name === slug),
    )
    .map(({ path }) => `[${path.split("/").at(-1)!.replaceAll("-", " ")}](/${path})`);
  return [
    apis.length ? `## Common APIs\n\n${apis.map((link) => `- ${link}`).join("\n")}` : "",
    modules.length
      ? `For configuration and examples, read ${[...new Map(modules.map((link) => [link.slice(link.indexOf("](")), link])).values()].slice(0, 3).join(", ")}.`
      : "",
    guides.length ? `For a complete workflow, follow ${guides.join(", ")}.` : "",
    ...frontendUsage
      .filter(({ packages }) => packages.some((name) => name === slug))
      .map(
        ({ title, href }) =>
          `## Frontend usage\n\n[${title}](${href}) shows the client side of this capability.`,
      ),
  ]
    .filter(Boolean)
    .join("\n\n");
}

/** Lists every cataloged package and its public authoring entrypoints in the reference overview.
 * @returns Generated Markdown shared by rendering, search, and page copying. */
export function referenceOverview(): string {
  return [
    "{/* Generated by apps/docs/scripts/generate.ts. Do not edit. */}",
    ...(["core", "integrations"] as const).map((group) => {
      const rows = apiPackageDefinitions
        .filter((definition) => definition.group === group)
        .map(({ slug, title, packageName }) => {
          const apis = authoringLinks(slug);
          return `| [${title}](/docs/api/${slug}) | \`${packageName}\` | ${apis.join(", ") || "See package reference"} |`;
        });
      const title = group === "core" ? "Core packages" : "Integrations";
      return `### ${title}\n\n| Reference | Package | Common APIs |\n| --- | --- | --- |\n${rows.join("\n")}`;
    }),
  ].join("\n\n");
}

/** Links symbols to their defining package, including integration APIs cataloged with application setup.
 * @param slug - Reference package route. @returns Unique links to existing generated symbol headings. */
function authoringLinks(slug: string): string[] {
  const definition = apiPackageDefinitions.find((item) => item.slug === slug);
  if (!definition) return [];
  const names = features
    .flatMap(({ entrypoints }) => entrypoints)
    .filter(({ source }) => source.startsWith(`${definition.directory}/src/`))
    .map(({ name }) => name);
  return [...new Set(names)].map((name) => `[${name}](/docs/api/${slug}#${name.toLowerCase()})`);
}
