/**
 * Renders the Inspector API reference from the routes the Inspector router registers, so the
 * development protocol page lists every endpoint with its version and authentication.
 */
import { inspectorApiReference, type InspectorEndpointReference } from "relkit/inspector-api";

const SERVERS: Record<InspectorEndpointReference["server"], string> = {
  bridge: "Bridge",
  application: "Application",
  inspector: "Inspector",
};

/**
 * Builds the complete MDX page.
 * @param endpoints - Reference entries; defaults to the live router installation.
 * @returns MDX source with one table row per endpoint.
 */
export async function renderInspectorApiReference(
  endpoints?: readonly InspectorEndpointReference[],
): Promise<string> {
  const rows = endpoints ?? (await inspectorApiReference());
  const authentication = [...new Set(rows.map((row) => row.authentication))];
  const note = (row: InspectorEndpointReference) =>
    `[${authentication.indexOf(row.authentication) + 1}]`;
  return `---
title: Inspector API reference
description: Generated list of every Inspector API endpoint, with its version and authentication.
search:
  exclude: true
sidebar:
  icon: radar
---

{/* Generated by apps/docs/scripts/generate.ts from relkit/inspector-api. Do not edit. */}

The Inspector API is a versioned development protocol. The bundled Inspector UI uses it, and so can other clients, such as [\`relkit mcp\`](/docs/modules/operations/mcp). It runs only in development: production builds do not start the bridge.

A running \`relkit dev\` session writes a private descriptor to \`.relkit/connections\` in the project. The descriptor holds the bridge address (\`endpoint\`), \`projectId\`, \`sessionId\` and a random \`token\`. A client reads it, calls the handshake, and then calls the endpoints below through the bridge. Send \`x-relkit-api-version: 1\` to pin the version; a different version fails with \`RELKIT_INSPECTOR_API_VERSION_UNSUPPORTED\`.

## Authentication

${authentication.map((text, index) => `${index + 1}. ${text}`).join("\n")}

## Endpoints

| Method | Path | Version | Server | Authentication | Description |
| --- | --- | --- | --- | --- | --- |
${rows
  .map(
    (row) =>
      `| ${row.method} | \`${row.path}\` | ${row.version} | ${SERVERS[row.server]} | ${note(row)} | ${row.summary.replaceAll("|", "\\|")} |`,
  )
  .join("\n")}
`;
}
