/** Renders the Core and Labs tables of the maturity page from the repository's maturity table. */
import { MATURITY_FEATURES, readLabsRoutes, type MaturityTier } from "../../../scripts/maturity.js";

/** Lists the routes of pages that set `labs: true`, for the badge above each such page.
 * @param root - Repository root. @returns JSON for `_snippets/generated/labs-routes.json`. */
export function labsRoutes(root: string): string {
  return JSON.stringify(readLabsRoutes(root));
}

/** Renders one table per tier, linking each feature to its first docs page.
 * @returns MDX for `_snippets/generated/maturity.mdx`. */
export function maturityTables(): string {
  const table = (tier: MaturityTier) =>
    [
      "| Feature | Packages | Notes |",
      "| --- | --- | --- |",
      ...MATURITY_FEATURES.filter((feature) => feature.tier === tier).map(
        ({ name, packages, docs, note }) =>
          `| ${docs[0] ? `[${name}](${docs[0]})` : name} | ${
            packages.map((item) => `\`${item}\``).join(", ") || "—"
          } | ${note ?? ""} |`,
      ),
    ].join("\n");
  return `{/* Generated by apps/docs/scripts/generate.ts from scripts/maturity.ts. Do not edit. */}\n\n## Core\n\n${table("core")}\n\n## Labs\n\n${table("labs")}\n`;
}

/** Lists the feature names of each tier for the roadmap page, linking each to its first docs page.
 * @returns MDX for `_snippets/generated/roadmap-status.mdx`. */
export function roadmapStatus(): string {
  const list = (tier: MaturityTier) =>
    MATURITY_FEATURES.filter((feature) => feature.tier === tier)
      .map(({ name, docs }) => `- ${docs[0] ? `[${name}](${docs[0]})` : name}`)
      .join("\n");
  const count = (tier: MaturityTier) =>
    MATURITY_FEATURES.filter((feature) => feature.tier === tier).length;
  return `{/* Generated by apps/docs/scripts/generate.ts from scripts/maturity.ts. Do not edit. */}

### Core: ${count("core")} features

${list("core")}

### Labs: ${count("labs")} features

${list("labs")}
`;
}
