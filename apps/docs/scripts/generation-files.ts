/** Discovers content and prunes only generator-owned output; checks never write. */
import { readdir, readFile, rm } from "node:fs/promises";
import { join } from "node:path";

/** Lists files deterministically, treating an absent output folder as empty.
 * @param directory - Existing or not-yet-generated directory. @returns Sorted paths. */
export async function contentFiles(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true }).catch(
    (error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return [];
      throw error;
    },
  );
  const files: string[] = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await contentFiles(path)));
    else files.push(path);
  }
  return files.sort();
}

/** Removes obsolete generated files while retaining authored content.
 * @param directory - Content root. @param expected - Absolute current output paths.
 * @param checkOnly - Report stale outputs without deleting. @returns Completion. */
export async function pruneGenerated(
  directory: string,
  expected: ReadonlySet<string>,
  checkOnly: boolean,
): Promise<void> {
  for (const path of await contentFiles(directory)) {
    if (expected.has(path)) continue;
    const owned =
      path.includes("/_snippets/") ||
      path.includes("/generated/") ||
      path.endsWith("/meta.json") ||
      (await readFile(path, "utf8")).includes("Generated by apps/docs/scripts/generate.ts");
    if (!owned) continue;
    if (checkOnly) throw new Error(`Generated documentation is stale: ${path}`);
    await rm(path);
  }
}
